/*
 * A variant is the same product in a different shape. It carries its own price and cost
 * rather than a delta, so a price is always read rather than computed from a chain of
 * adjustments nobody can follow.
 */
create table product_variant (
    id         bigint        generated by default as identity primary key,
    product_id bigint        not null references product (id),
    name       varchar(120)  not null,
    unit_price numeric(14, 2) not null,
    unit_cost  numeric(14, 2) not null,
    constraint uq_variant_product_name unique (product_id, name)
);

