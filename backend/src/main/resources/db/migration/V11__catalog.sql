create table price_list (
    id      bigint       generated by default as identity primary key,
    name    varchar(120) not null unique,
    -- Null would mean a list that applies to everyone; every seeded list is tier-bound.
    tier_id bigint       references customer_tier (id),
    active  boolean      not null default true
);

-- At most one live list per tier, enforced here rather than in a service that could be
-- bypassed. Two active lists for one tier would make a price ambiguous.
create unique index uq_price_list_active_tier on price_list (tier_id) where active;

create table price_list_item (
    id            bigint         generated by default as identity primary key,
    price_list_id bigint         not null references price_list (id) on delete cascade,
    product_id    bigint         not null references product (id),
    unit_price    numeric(14, 2) not null,
    constraint uq_price_list_product unique (price_list_id, product_id)
);

